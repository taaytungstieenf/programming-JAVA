package SyntaxA_Introduction;

public class HelloWorld {
    public static void main(String[] args) {
        System.out.println("Hello, Tae!");
    }
}

// public		    access modifier, can access this class from terminal
// static		    flexibility call method, without `static` you have to create object to call method
// void		        method does not return a value
// main		        not an arbitrary name, Java regulate a method entry is *main*
// String[] args	receive arguments from command line